CREATE VIEW carrier_count AS
SELECT desynpuf_id_cl, EXTRACT(YEAR FROM clm_thru_dt_cl) AS clm_yr , COUNT(clm_id_cl) AS crrr_cnt_clms
FROM carrier_claims_half1
GROUP BY 1, 2
ORDER BY 2;